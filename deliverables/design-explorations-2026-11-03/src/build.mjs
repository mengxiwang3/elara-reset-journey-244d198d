// Inlines src/content.js + shared.{css,js} + one concept into a self-contained
// ../<concept>.html. Run: node src/build.mjs   (from the workspace folder)
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "..");
const read = (f) => readFileSync(join(here, f), "utf8");

const concepts = {
  a: { title: "Elara · Sesión A: Paso a paso", h: "A · Camino guiado paso a paso",
       p: "Una pantalla por momento: por qué hoy, la elección, lo que notó Elara, «Para llevarte», cierre. Lo más cercano a la arquitectura actual de pasos." },
  b: { title: "Elara · Sesión B: Conversación", h: "B · Conversación con Elara",
       p: "Un solo hilo con Elara. La elección y «Para llevarte» siguen siendo entradas estructuradas, dentro de la conversación." },
  c: { title: "Elara · Sesión C: Tarjeta para llevar", h: "C · Primero la acción, luego la tarjeta",
       p: "Empieza mostrando lo que se lleva hoy: una tarjeta que se va llenando con cada paso y queda en Hoy y en Tu colección." },
};

for (const [k, c] of Object.entries(concepts)) {
  if (!existsSync(join(here, k + ".js"))) continue;
  const html = `<!doctype html>
<html lang="es">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<title>${c.title}</title>
<!-- Generated by src/build.mjs from src/content.js, src/shared.*, src/${k}.*  Do not edit by hand. -->
<style>
${read("shared.css")}
${read(k + ".css")}
</style>
</head>
<body>
<div class="stage">
  <div class="phone" aria-label="Prototipo en un teléfono">
    <div id="app"></div>
    <div id="sheet"></div>
    <div id="toast" role="status" aria-live="polite"></div>
  </div>
  <aside class="rev" aria-label="Panel de revisión">
    <h1>${c.h}</h1>
    <p>${c.p}</p>
    <p><span class="rtag">Contenido actual de la app (aprobación por confirmar)</span></p>
    <div id="rev-controls"></div>
    <p class="fine">Prototipo clicable. Respuestas de Elara pre-escritas y sintéticas («Respuesta simulada»); ningún dato real, ninguna llamada a IA. El estado se guarda solo en este navegador.</p>
    <p><a href="index.html">← Las tres propuestas</a></p>
  </aside>
</div>
<script>
${read("content.js")}
${read("shared.js")}
${read(k + ".js")}
</script>
</body>
</html>
`;
  writeFileSync(join(out, k + ".html"), html);
  console.log("wrote", k + ".html", html.length, "bytes");
}
